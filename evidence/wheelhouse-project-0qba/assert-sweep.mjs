import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const [logPath, inventoryPath, exitPath, stderrPath, failureJSON] = process.argv.slice(2);
for (const p of [logPath, inventoryPath, exitPath, stderrPath]) assert(fs.statSync(p).isFile(), `missing regular input ${p}`);
assert(fs.statSync(logPath).size > 0); assert(fs.statSync(inventoryPath).size > 0);
const log=fs.readFileSync(logPath,'utf8'), inventory=fs.readFileSync(inventoryPath,'utf8').trim().split('\n').map(p=>path.basename(p));
assert.equal(new Set(inventory).size,inventory.length,'duplicate inventory');
const failures=JSON.parse(failureJSON); assert(Array.isArray(failures)); assert.equal(new Set(failures).size,failures.length);
for(const f of failures) assert(inventory.includes(f),'expected failure is an actual suite');
const rows=[...log.matchAll(/^selftest-sweep: (START|PASS|FAIL) (.+\.selftest\.sh)(?: rc=\d+)?$/gm)].map(m=>[m[1],path.basename(m[2])]);
const bridges=rows.filter(r=>r[1]==='bridge.selftest.sh'),inner=rows.filter(r=>r[1]!=='bridge.selftest.sh');
const names=kind=>inner.filter(r=>r[0]===kind).map(r=>r[1]).sort();
assert.deepEqual(names('START'),[...inventory].sort(),'START inventory differs');
assert.deepEqual(names('PASS'),inventory.filter(n=>!failures.includes(n)).sort(),'PASS inventory differs');
assert.deepEqual(names('FAIL'),[...failures].sort(),'FAIL inventory differs');
const terminal=failures.length?'FAIL':'PASS',rc=failures.length?1:0;
assert.deepEqual(bridges,[['START','bridge.selftest.sh'],[terminal,'bridge.selftest.sh']]);
const aggregates=[...log.matchAll(/^selftest-sweep: (PASS|FAIL) \((?:(\d+) failure\(s\) of )?(\d+) suite\(s\)\)$/gm)].map(m=>`${m[1]}:${m[2]??0}:${m[3]}`).sort();
assert.deepEqual(aggregates,[`${terminal}:${failures.length}:`+inventory.length,`${terminal}:${rc}:1`].sort());
assert.equal(fs.readFileSync(exitPath,'utf8'),rc+'\n');
assert.match(log,new RegExp(`umbrella safety: PASS .*test exit=${rc}; signal=null`));assert(!/^STOP /m.test(log));
console.log(JSON.stringify({innerStart:names('START').length,innerPass:names('PASS').length,innerFail:names('FAIL').length,failedSuites:names('FAIL'),bridgeStart:1,bridgeTerminal:terminal,inventoryExact:true,exit:rc}));
